import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourceUrl = new URL("../public/brand/theme-init.js", import.meta.url);
const outputUrl = new URL("../src/app/theme-integrity.generated.ts", import.meta.url);
const source = await readFile(sourceUrl);
const integrity = `sha256-${createHash("sha256").update(source).digest("base64")}`;
const generated = `// Generated by scripts/generate-theme-integrity.mjs. Do not edit.\nexport const themeInitIntegrity = ${JSON.stringify(integrity)};\n`;

let previous = "";
try {
  previous = await readFile(outputUrl, "utf8");
} catch {
  previous = "";
}

if (previous !== generated) {
  await writeFile(outputUrl, generated, "utf8");
  process.stdout.write(`Generated ${fileURLToPath(outputUrl)}\n`);
}
